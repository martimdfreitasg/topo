#' Plot Alignment and Cluster Ribbon
#'
#' Visualizes the sequence alignment (residues vs. gaps)
#' alongside its cluster membership ribbon, ordered according to the
#' UPGMA dendrogram without drawing the tree branches.
#'
#' @details
#' Residues are drawn in dark gray (`"#333333"`) and gaps in white
#' (`"#ffffff"`). Optional `highlight_regions` recolor occupied residue cells
#' within specified alignment column ranges to mark domains or motifs of
#' interest; if two regions overlap, a warning is issued and the earlier region
#' takes precedence. Topologies classified as `"Unassigned"` by
#' `topoclust()` are colored neutral gray (`"#BDBDBD"`).
#'
#' @param fasta_path Path to a FASTA alignment file or an `ape::AAbin` /
#'   `ape::DNAbin` object. Optional if `dist_mat` is provided.
#' @param metric Distance metric (`"gaps"`, `"residues"`, or `"both"`).
#' @param highlight_regions Optional list of positive integer vectors defining
#'   alignment column indices to highlight.
#' @param highlight_colors Optional character vector of colors corresponding to
#'   `highlight_regions`. Defaults to `"Set 2"` from `grDevices::hcl.colors()`.
#' @param dist_mat Optional pre-calculated `dist` object from `topodist()`.
#' @param cluster_mapping Optional pre-calculated mapping `data.frame` from
#'   `topoclust()`.
#' @param deepSplit Cluster splitting sensitivity passed to `topoclust()` when
#'   `cluster_mapping` is `NULL`. Default is `2`.
#' @param minClusterSize Minimum cluster size passed to `topoclust()` when
#'   `cluster_mapping` is `NULL`. Default is `2`.
#'
#' @return A `ggtree`/`ggplot` object containing the alignment topology heatmap
#'   and cluster ribbon.
#'
#' @references
#' Yu, G., Smith, D. K., Zhu, H., Guan, Y., & Lam, T. T.-Y. (2017). ggtree: an
#' R package for visualization and annotation of phylogenetic trees with their
#' covariates and other associated data. *Methods in Ecology and Evolution*,
#' 8(1), 28--36. \doi{10.1111/2041-210X.12628}
#'
#' @export
#' @examples
#' fasta_path = system.file("extdata", "test.fasta", package = "topo")
#' map_plot = topomap(fasta_path, metric = "gaps")
#' map_plot
topomap = function(fasta_path = NULL,
                    metric = c("gaps", "residues", "both"),
                    highlight_regions = NULL,
                    highlight_colors = NULL,
                    dist_mat = NULL,
                    cluster_mapping = NULL,
                    deepSplit = 2,
                    minClusterSize = 2) {

  metric = match.arg(metric)

  if (is.null(dist_mat)) {
    dist_mat = topodist(fasta_path, metric = metric)
  }
  if (!inherits(dist_mat, "dist")) {
    stop("'dist_mat' must be a 'dist' object produced by topodist().", call. = FALSE)
  }
  if (attr(dist_mat, "Size") < 2L) {
    stop("At least 2 distinct topologies are required for plotting.", call. = FALSE)
  }

  unique_bin = attr(dist_mat, "matrix")
  if (is.null(unique_bin)) {
    stop("'dist_mat' must contain the binary matrix attribute generated by topodist().", call. = FALSE)
  }

  if (is.null(cluster_mapping)) {
    cluster_mapping = topoclust(
      fasta_path = fasta_path,
      metric = metric,
      dist_mat = dist_mat,
      deepSplit = deepSplit,
      minClusterSize = minClusterSize
    )
  }

  aln_dend = stats::hclust(dist_mat, method = "average")
  tree = ape::as.phylo(aln_dend)
  tree = ape::reorder.phylo(tree, "cladewise")

  p_blank_tree = ggtree::ggtree(tree, color = NA)

  .build_topo_heatmap(
    p_base = p_blank_tree,
    tree = tree,
    unique_bin = unique_bin,
    cluster_mapping = cluster_mapping,
    highlight_regions = highlight_regions,
    highlight_colors = highlight_colors
  )
}
